    # 请详解

    ---

     

    **一、背景与动因**
    -----------

    ### 大模型记忆需求的提出

     
    随着 LLM 在科研、产业和生活中的广泛应用，单次推理或单次检索的“静态”方式已难满足多轮对话、长期任务协作、个性化推荐等场景对“持续记忆” 的需求。用户和开发者都在追问：如何让模型「记得」更多历史信息、并在后续交互中有效调用？
     

    ### 现有解决方案的局限
     

    ### 全局记忆（Global Memory）

    ：类似 OpenAI 当前的全局上下文窗口，容易因长度膨胀导致 Token 开销大幅增加。
     
    ### 传统 RAG

    ：基于向量检索的外部知识库，往往不能充分利用模型内部的激活或参数记忆，也缺乏高效的调度机制。
     
    ### MemOS 的提出



     
    由记忆张量（上海）科技联合多所高校与企业发布，目标是打造一个“像操作系统一样”专门管理 LLM 记忆的工业级框架，真正把“记忆”视作与算力、内存同等重要的资源来调度和优化。

     

    ---

     

    **二、核心性能数据**
    ------------

    #### 准确性提升

    ：相比 OpenAI 的全局记忆方案，在标准大模型记忆评测集上平均准确性提升 **38.97%**。
     
    #### Token 开销下降

    ：平均所需上下文 Token 数量减少 **60.95%**，大幅节省调用成本。
     
    #### 时序推理

    ：在考验时序建模与检索能力的 Temporal Reasoning 任务上，相对提升 **159%**，展现对事件顺序和时间逻辑记忆的显著优势。

     
    这些数据表明，MemOS 在“更准、更省、更擅长时间线思考”三方面都达到了 SOTA 水平。

     

